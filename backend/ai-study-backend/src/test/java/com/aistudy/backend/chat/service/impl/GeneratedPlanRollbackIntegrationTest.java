package com.aistudy.backend.chat.service.impl;

import com.aistudy.backend.chat.dto.AIPlanResultDTO;
import com.aistudy.backend.plan.entity.StudyPlan;
import com.aistudy.backend.plan.service.StudyPlanService;
import com.aistudy.backend.task.entity.StudyTask;
import com.aistudy.backend.task.service.TaskService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.test.context.junit.jupiter.SpringJUnitConfig;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.annotation.EnableTransactionManagement;

import javax.sql.DataSource;
import java.util.List;
import java.util.concurrent.atomic.AtomicInteger;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

/**
 * Verifies a real Spring transaction through JDBC/H2.
 * H2 is test-only; production uses MySQL. Neither the real database nor API is touched.
 */
@SpringJUnitConfig(GeneratedPlanRollbackIntegrationTest.TestConfig.class)
class GeneratedPlanRollbackIntegrationTest {

    @Autowired private GeneratedPlanPersistenceService persistenceService;
    @Autowired private JdbcTemplate jdbc;
    @Autowired private StudyPlanService planService;
    @Autowired private TaskService taskService;

    @Configuration
    @EnableTransactionManagement
    @Import(GeneratedPlanPersistenceService.class)
    static class TestConfig {
        @Bean
        DataSource dataSource() {
            DriverManagerDataSource ds = new DriverManagerDataSource();
            ds.setDriverClassName("org.h2.Driver");
            ds.setUrl("jdbc:h2:mem:ai_plan_rollback_test;DB_CLOSE_DELAY=-1");
            ds.setUsername("sa");
            ds.setPassword("");
            return ds;
        }

        @Bean
        JdbcTemplate jdbcTemplate(DataSource dataSource) {
            return new JdbcTemplate(dataSource);
        }

        @Bean
        PlatformTransactionManager transactionManager(DataSource dataSource) {
            return new DataSourceTransactionManager(dataSource);
        }

        @Bean
        StudyPlanService studyPlanService() {
            return mock(StudyPlanService.class);
        }

        @Bean
        TaskService taskService() {
            return mock(TaskService.class);
        }
    }

    @BeforeEach
    void setup() {
        reset(planService, taskService);
        jdbc.execute("DROP TABLE IF EXISTS tasks");
        jdbc.execute("DROP TABLE IF EXISTS plans");
        jdbc.execute("CREATE TABLE plans (id INT PRIMARY KEY, title VARCHAR(200))");
        jdbc.execute("CREATE TABLE tasks (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, plan_id INT, title VARCHAR(200))");
        when(planService.add(any(StudyPlan.class))).thenAnswer(invocation -> {
            StudyPlan plan = invocation.getArgument(0);
            jdbc.update("INSERT INTO plans (id, title) VALUES (?, ?)", 42, plan.getTitle());
            plan.setId(42);
            return 1;
        });
    }

    private static AIPlanResultDTO validPlan() {
        AIPlanResultDTO plan = new AIPlanResultDTO();
        plan.setTitle("Java 学习计划");
        plan.setContent("从基础开始学习");
        plan.setStartDate("2026-11-21");
        plan.setEndDate("2026-11-22");
        plan.setTargetHours(5);

        AIPlanResultDTO.TaskDTO a = new AIPlanResultDTO.TaskDTO();
        a.setTitle("任务一");
        a.setContent("变量与循环");
        a.setTaskDate("2026-11-21");

        AIPlanResultDTO.TaskDTO b = new AIPlanResultDTO.TaskDTO();
        b.setTitle("任务二");
        b.setContent("集合");
        b.setTaskDate("2026-11-22");
        plan.setTasks(List.of(a, b));
        return plan;
    }

    @Test
    void shouldCommitBothPlanAndTasksOnSuccess() {
        when(taskService.add(any(StudyTask.class))).thenAnswer(invocation -> {
            StudyTask task = invocation.getArgument(0);
            jdbc.update("INSERT INTO tasks (plan_id, title) VALUES (?, ?)",
                    task.getPlanId(), task.getTitle());
            return 1;
        });

        persistenceService.save(7, validPlan());

        assertEquals(1L, jdbc.queryForObject("SELECT COUNT(*) FROM plans", Long.class));
        assertEquals(2L, jdbc.queryForObject("SELECT COUNT(*) FROM tasks", Long.class));
    }

    @Test
    void shouldRollbackPlanAndFirstTaskWhenSecondTaskFails() {
        AtomicInteger attempts = new AtomicInteger();
        when(taskService.add(any(StudyTask.class))).thenAnswer(invocation -> {
            int count = attempts.incrementAndGet();
            if (count == 2) {
                throw new IllegalStateException("模拟第二个任务写入失败");
            }
            StudyTask task = invocation.getArgument(0);
            jdbc.update("INSERT INTO tasks (plan_id, title) VALUES (?, ?)",
                    task.getPlanId(), task.getTitle());
            return 1;
        });

        assertThrows(IllegalStateException.class,
                () -> persistenceService.save(7, validPlan()));

        assertEquals(2, attempts.get());
        assertEquals(0L, jdbc.queryForObject("SELECT COUNT(*) FROM plans", Long.class));
        assertEquals(0L, jdbc.queryForObject("SELECT COUNT(*) FROM tasks", Long.class));
    }
}
