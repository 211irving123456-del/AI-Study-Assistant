package com.aistudy.backend.task.mapper;

import com.aistudy.backend.task.entity.StudyTask;
import org.apache.ibatis.mapping.Environment;
import org.apache.ibatis.session.Configuration;
import org.apache.ibatis.session.SqlSession;
import org.apache.ibatis.session.SqlSessionFactory;
import org.apache.ibatis.session.SqlSessionFactoryBuilder;
import org.apache.ibatis.transaction.jdbc.JdbcTransactionFactory;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.time.LocalDate;

import static org.junit.jupiter.api.Assertions.assertEquals;

/**
 * Executes TaskMapper's real annotated SQL against an isolated in-memory database.
 * Does not connect to the developer's local MySQL database.
 */
class TaskOwnershipIntegrationTest {

    private JdbcTemplate jdbc;
    private SqlSessionFactory sqlSessionFactory;

    @BeforeEach
    void setUp() {
        DriverManagerDataSource dataSource = new DriverManagerDataSource();
        dataSource.setDriverClassName("org.h2.Driver");
        dataSource.setUrl("jdbc:h2:mem:task_ownership_test;DB_CLOSE_DELAY=-1");
        dataSource.setUsername("sa");
        dataSource.setPassword("");

        jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("DROP TABLE IF EXISTS study_task");
        jdbc.execute("DROP TABLE IF EXISTS study_plan");
        jdbc.execute("CREATE TABLE study_plan (id INT PRIMARY KEY, user_id INT NOT NULL)");
        jdbc.execute("""
                CREATE TABLE study_task (
                  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  user_id INT NOT NULL,
                  plan_id INT NOT NULL,
                  title VARCHAR(200),
                  content VARCHAR(1000),
                  task_date DATE,
                  status INT,
                  create_time TIMESTAMP
                )
                """);
        jdbc.update("INSERT INTO study_plan (id, user_id) VALUES (101, 7)");
        jdbc.update("INSERT INTO study_plan (id, user_id) VALUES (202, 8)");

        Configuration config = new Configuration(
                new Environment("test", new JdbcTransactionFactory(), dataSource));
        config.setMapUnderscoreToCamelCase(true);
        config.addMapper(TaskMapper.class);
        sqlSessionFactory = new SqlSessionFactoryBuilder().build(config);
    }

    private StudyTask taskFor(int planId) {
        StudyTask task = new StudyTask();
        task.setUserId(7);
        task.setPlanId(planId);
        task.setTitle("测试学习任务");
        task.setContent("验证计划归属权限");
        task.setTaskDate(LocalDate.of(2026, 11, 22));
        task.setStatus(0);
        return task;
    }

    @Test
    void ownerCanAddTaskToOwnPlan() {
        try (SqlSession session = sqlSessionFactory.openSession(true)) {
            int changed = session.getMapper(TaskMapper.class).insert(taskFor(101));
            assertEquals(1, changed);
        }
        assertEquals(1L, jdbc.queryForObject(
                "SELECT COUNT(*) FROM study_task WHERE user_id = 7 AND plan_id = 101",
                Long.class));
    }

    @Test
    void anotherUsersPlanCannotReceiveTask() {
        try (SqlSession session = sqlSessionFactory.openSession(true)) {
            int changed = session.getMapper(TaskMapper.class).insert(taskFor(202));
            assertEquals(0, changed);
        }
        assertEquals(0L, jdbc.queryForObject("SELECT COUNT(*) FROM study_task", Long.class));
    }

    @Test
    void missingPlanCannotReceiveTask() {
        try (SqlSession session = sqlSessionFactory.openSession(true)) {
            int changed = session.getMapper(TaskMapper.class).insert(taskFor(999));
            assertEquals(0, changed);
        }
        assertEquals(0L, jdbc.queryForObject("SELECT COUNT(*) FROM study_task", Long.class));
    }
}
